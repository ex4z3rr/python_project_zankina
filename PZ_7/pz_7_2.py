#Дана строка, содержащая полное имя файла.
# Выделить из этой строки название первого каталога (без символов «\»).
# Если файл содержится в корневом каталоге, то вывести символ «\».

while True:  # обработка исключений
    try:
        file_path = input("Введите полное имя файла (например, C:\\Users\\doc.txt): ")
        if "\\" not in file_path:
            raise ValueError
        break
    except ValueError:
        print("Неправильно ввели! Полное имя файла должно содержать символ '\\'.")

print("Исходная строка:", file_path)

# Разбиваем путь по разделителю каталогов '\'
parts = file_path.split("\\")

# Если частей больше двух (диск, каталог, ..., имя файла), берем первый каталог
if len(parts) > 2 and parts[1] != "":
    result = parts[1]
else:
    result = "\\"

print("Результирующая строка:", result)
