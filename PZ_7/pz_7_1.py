#Дана непустая строка S.
# Вывести строку, содержащую символы строки S, между которыми вставлено по одному пробелу.

while True:  # обработка исключений
    try:
        s = input("Введите непустую строку S: ")
        if len(s) == 0:
            raise ValueError
        break
    except ValueError:
        print("Неправильно ввели! Строка не должна быть пустой.")

print("Исходная строка:", s)

# Объединяем символы строки через пробел с помощью метода join()
new_string = " ".join(s)

print("Результирующая строка:", new_string)
