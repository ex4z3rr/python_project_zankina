#Дано двузначное число. Вывести вначале его левую цифру (десятки),
#а затем - его правую цифру (единицы). Для нахождения десятков испольовать операцию деления нацело,
#для нахождения единиц - операцию взятия остатков от деления.
n = int(input("Введите двузначное число"))
n = n // 10, n % 10
print (n)