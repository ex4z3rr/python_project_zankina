#Дан список A размера N (N — четное число). Вывести его элементы с четными
#номерами в порядке возрастания номеров: A2, A4, A6, ..., AN. Условный оператор не
#использовать.
import random

while True:  # обработка исключений
    try:
        n = int(input("Введите четный размер списка N: "))
        if n <= 0 or n % 2 != 0:
            raise ValueError
        break
    except ValueError:
        print("Неправильно ввели! N должно быть положительным четным числом.")

a = []
i = 0
while i < n:
    a.append(random.randint(0, 100))
    i += 1

print("Исходный список:", a)

# Элементы с четными порядковыми номерами (A2, A4, ...) имеют индексы 1, 3, ...
result = a[1::2]
print("Элементы с четными номерами:", result)
