#Дан список размера N. Осуществить сдвиг элементов списка влево на одну позицию (при этом AN
# перейдет в AN-1, AN-1 — в AN-2, ..., A2 — в A1, а исходное значение первого элемента будет потеряно).
# Последний элемент полученного списка положить равным 0.
import random


while True:  # обработка исключений
    try:
        n = int(input("Введите размер списка N: "))
        if n <= 0:
            raise ValueError
        break
    except ValueError:
        print("Неправильно ввели! N должно быть положительным целым числом.")

a = []
i = 0
while i < n:
    a.append(random.randint(0, 100))
    i += 1

print("Исходный список:", a)

# Сдвигаем элементы влево на одну позицию
i = 0
while i < n - 1:
    a[i] = a[i + 1]
    i += 1
a[n - 1] = 0

print("Список после сдвига влево:", a)
