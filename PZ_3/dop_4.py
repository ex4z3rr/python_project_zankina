#Условие: Дано целое число. Если оно является положительным, то прибавить к нему 20, в противном случае вычесть из него 5.

x = input("Введите целое число: ")

while type(x) != int:  # обработка исключений
    try:
        x = int(x)
    except ValueError:
        print("Неправильно ввели!")
        x = input("Введите целое число: ")

if x > 0:
    x += 20
else:
    x -= 5

print("Результат =", x)
