#Условие: Дано целое число, лежащее в диапазоне 1–999. Вывести его строку-описание вида «четное двузначное число», «нечетное трехзначное число» и т. д.

n = input("Введите число от 1 до 999: ")

while type(n) != int:  # обработка исключений
    try:
        n = int(n)
        if not (1 <= n <= 999):
            print("Число должно быть в диапазоне от 1 до 999!")
            n = input("Введите число от 1 до 999: ")
    except ValueError:
        print("Неправильно ввели!")
        n = input("Введите число от 1 до 999: ")

# Определение четности
if n % 2 == 0:
    parity = "четное"
else:
    parity = "нечетное"

# Определение количества знаков
if n < 10:
    digits = "однозначное"
elif n < 100:
    digits = "двузначное"
else:
    digits = "трехзначное"

print(f"{parity} {digits} число")