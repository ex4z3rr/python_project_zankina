#Условие: Даны два целых числа: A, B. Проверить истинность высказывания: «Числа A и B имеют одинаковую четность».

a, b = input("Введите первое число: "), input("Введите второе число: ")

while type(a) != int:  # обработка исключений
    try:
        a = int(a)
    except ValueError:
        print("Неправильно ввели!")
        a = input("Введите первое число: ")

while type(b) != int:  # обработка исключений
    try:
        b = int(b)
    except ValueError:
        print("Неправильно ввели!")
        b = input("Введите второе число: ")

# У чисел одинаковая четность, если остатки от деления на 2 равны
res = (a % 2 == b % 2)
print("Истинность высказывания:", res)