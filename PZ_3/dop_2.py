#Условие: Ввести число. Если оно четное, разделить его на 4, если нечетное — умножить на 5.

n = input("Введите число: ")

while type(n) != int:  # обработка исключений
    try:
        n = int(n)
    except ValueError:
        print("Неправильно ввели!")
        n = input("Введите число: ")

if n % 2 == 0:
    n /= 4
else:
    n *= 5

print("Результат =", n)
