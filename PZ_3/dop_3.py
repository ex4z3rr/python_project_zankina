#Условие: Ввести двузначное число. Если сумма цифр числа четная, то увеличить число на 2, в противном случае уменьшить на 2.

num = input("Введите двузначное число: ")

while type(num) != int:  # обработка исключений
    try:
        num = int(num)
        if not (-99 <= num <= -10 or 10 <= num <= 99):
            print("Число должно быть двузначным!")
            num = input("Введите двузначное число: ")
    except ValueError:
        print("Неправильно ввели!")
        num = input("Введите двузначное число: ")

# Находим десятки и единицы (работает и для отрицательных чисел)
tens = abs(num) // 10
units = abs(num) % 10
digit_sum = tens + units

if digit_sum % 2 == 0:
    num += 2
else:
    num -= 2

print("Результат =", num)
